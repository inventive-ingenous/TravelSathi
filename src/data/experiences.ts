export const DEFAULT_CATEGORY_META = { label: 'Explore', emoji: '📍', tone: '#4E6BD6' };

export const getCategoryMeta = (cat?: string): { label: string; emoji: string; tone: string } => {
  if (!cat) return DEFAULT_CATEGORY_META;
  const key = String(cat).toLowerCase().trim();
  if (CATEGORY_META[key]) return CATEGORY_META[key];

  if (['restaurant', 'cafe', 'food', 'bakery', 'meal_takeaway', 'meal_delivery'].some((x) => key.includes(x))) return CATEGORY_META.food;
  if (['museum', 'culture', 'tourist_attraction', 'point_of_interest', 'sightseeing'].some((x) => key.includes(x))) return CATEGORY_META.culture;
  if (['store', 'shopping_mall', 'shopping', 'clothing_store'].some((x) => key.includes(x))) return CATEGORY_META.shopping;
  if (['park', 'nature', 'zoo', 'campground', 'garden'].some((x) => key.includes(x))) return CATEGORY_META.nature;
  if (['place_of_worship', 'historical_landmark', 'heritage', 'history', 'church', 'hindu_temple', 'mosque'].some((x) => key.includes(x))) return CATEGORY_META.history;
  if (['bar', 'night_club', 'nightlife', 'pub'].some((x) => key.includes(x))) return CATEGORY_META.nightlife;
  if (['art_gallery', 'art'].some((x) => key.includes(x))) return CATEGORY_META.art;

  const formattedLabel = key.charAt(0).toUpperCase() + key.slice(1).replace(/_/g, ' ');
  return { label: formattedLabel, emoji: '📍', tone: '#4E6BD6' };
};

